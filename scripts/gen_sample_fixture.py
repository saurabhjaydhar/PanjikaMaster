#!/usr/bin/env python3
"""Generate app/lib/data/fixtures/sample_pack.g.dart from the sample packs (T-110).

The app must never ship sample data. Flutter can't exclude asset files per build mode,
so the sample packs become SQL INSERT statements in a Dart file that is only reachable
behind `kDebugMode`; release builds tree-shake it away, and ci-app's bundle check
proves it. `--check` (used by CI) fails if the generated file is stale.
"""

import sqlite3
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "data"))

from pack import sample, schema  # noqa: E402

DST = ROOT / "app" / "lib" / "data" / "fixtures" / "sample_pack.g.dart"
ROWS_PER_STATEMENT = 200


def literal(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, int | float):
        return repr(value)
    text = str(value)
    if '"' in text or "\n" in text:
        raise ValueError(f"unsupported character in fixture text: {text!r}")
    return "'" + text.replace("'", "''") + "'"


def statements() -> list[str]:
    out: list[str] = []
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:  # Windows
        paths = sample.build(Path(tmp))
        conns = [sqlite3.connect(p) for p in paths]
        for table in schema.PACK_TABLES:  # parents before children
            cols = schema.columns(conns[0], table)
            for conn in conns:
                rows = conn.execute(f"SELECT * FROM {table} ORDER BY rowid").fetchall()
                for i in range(0, len(rows), ROWS_PER_STATEMENT):
                    chunk = rows[i : i + ROWS_PER_STATEMENT]
                    values = ",".join("(" + ",".join(map(literal, r)) + ")" for r in chunk)
                    out.append(f"INSERT INTO {table} ({','.join(cols)}) VALUES {values};")
        for conn in conns:
            conn.close()
    return out


def verify(stmts: list[str]) -> None:
    """The statements must recreate exactly the rows of the sample packs."""
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:  # Windows
        expected: dict[str, int] = {}
        for p in sample.build(Path(tmp)):
            with sqlite3.connect(p) as conn:
                for t in schema.PACK_TABLES:
                    n = conn.execute(f"SELECT count(*) FROM {t}").fetchone()[0]
                    expected[t] = expected.get(t, 0) + n
    conn = schema.connect()
    for s in stmts:
        conn.execute(s)
    got = {t: conn.execute(f"SELECT count(*) FROM {t}").fetchone()[0] for t in schema.PACK_TABLES}
    assert got == expected, (got, expected)
    assert conn.execute("PRAGMA foreign_key_check").fetchall() == []


def render(stmts: list[str]) -> str:
    body = "\n".join(f'  r"{s}",' for s in stmts)
    return (
        "// GENERATED by scripts/gen_sample_fixture.py from data/pack/sample.py. Do not edit.\n"
        "// SAMPLE DATA (নমুনা): synthetic, not a panjika. Only reachable behind kDebugMode.\n"
        "// ignore_for_file: lines_longer_than_80_chars\n\n"
        f"const sampleMarker = '{sample.SAMPLE_MARKER}';\n\n"
        f"const samplePackStatements = <String>[\n{body}\n];\n"
    )


def main() -> int:
    stmts = statements()
    verify(stmts)
    content = render(stmts)
    if "--check" in sys.argv:
        if not DST.exists() or DST.read_text(encoding="utf-8") != content:
            print(f"{DST.relative_to(ROOT)} is stale: run python scripts/gen_sample_fixture.py")
            return 1
        print("sample_pack.g.dart is up to date")
        return 0
    DST.write_text(content, encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)}: {len(stmts)} statements, {len(content) // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
